import { basename, dirname, join } from "jsr:@std/path@1";

export interface HipfireBackend {
  kind: "hipfire";
  executable: string;
  vendor?: { manifest: string; artifact: string };
  home: string;
  listen: { host: string; port: number };
  tag: string;
  kvMode: string;
  maxSeq: number;
  ui: boolean;
  speculative:
    | { kind: "none" }
    | {
      kind: "dflash";
      model: { path: string; source: { url: string; size: number; sha256: string } };
      blockSize: number;
    };
  environment?: Record<string, string>;
  readyTimeoutSeconds?: number;
}

/** Model files a hipfire deployment serves; linked into the home under their own names. */
export interface HipfireModelFiles {
  model: string;
  draft?: string;
  vision?: string;
}

export const DEFAULT_HIPFIRE_READY_TIMEOUT_SECONDS = 600;

/** The daemon hipfire serve spawns; built next to the `hipfire` executable. */
export function hipfireDaemonPath(backend: HipfireBackend): string {
  return join(dirname(backend.executable), "daemon");
}

export function buildHipfireArgs(backend: HipfireBackend): string[] {
  return [
    "serve",
    `${backend.listen.host}:${backend.listen.port}`,
    "--model",
    backend.tag,
    "--spec",
    backend.speculative.kind === "dflash" ? "dflash" : "off",
    "--kv-mode",
    backend.kvMode,
    "--max-seq",
    String(backend.maxSeq),
    ...(backend.ui ? ["--ui"] : []),
  ];
}

/**
 * Process environment for hipfire serve. HIPFIRE_PREFILL_PROGRESS makes the
 * Responses stream carry prompt progress, which the proxy renders as the
 * prompt-evaluation trace. Declared `environment` entries win.
 */
export function buildHipfireEnvironment(
  backend: HipfireBackend,
  files: HipfireModelFiles,
): Record<string, string> {
  return {
    HIPFIRE_HOME: backend.home,
    HIPFIRE_LOCAL: "1",
    HIPFIRE_DAEMON_BIN: hipfireDaemonPath(backend),
    HIPFIRE_PREFILL_PROGRESS: "1",
    ...(backend.speculative.kind === "dflash"
      ? { HIPFIRE_DFLASH_BLOCK: String(backend.speculative.blockSize) }
      : {}),
    ...(files.vision ? { HIPFIRE_VISION_MODE: "on" } : {}),
    ...backend.environment,
  };
}

function tomlString(value: string): string {
  return JSON.stringify(value);
}

/**
 * The home's model catalog: `tag` served from the linked model file, and
 * `modelId` (what clients send) as an alias for it. hipfire only honours an
 * alias whose model entry has an explicit path.
 */
export function buildHipfireCatalog(
  backend: HipfireBackend,
  modelId: string,
  files: HipfireModelFiles,
): string {
  const modelPath = join(backend.home, "models", basename(files.model));
  return [
    "# Generated by lm-tools; rewritten on every start.",
    "schema_version = 1",
    "",
    "[aliases]",
    ...(modelId === backend.tag ? [] : [`${tomlString(modelId)} = ${tomlString(backend.tag)}`]),
    "",
    `[models.${tomlString(backend.tag)}]`,
    `registry_tag = ${tomlString(backend.tag)}`,
    `path = ${tomlString(modelPath)}`,
    "",
  ].join("\n");
}

async function replaceSymlink(target: string, link: string): Promise<void> {
  try {
    const existing = await Deno.lstat(link);
    if (!existing.isSymlink) throw new Error(`${link} exists and is not a symlink`);
    await Deno.remove(link);
  } catch (error) {
    if (!(error instanceof Deno.errors.NotFound)) throw error;
  }
  await Deno.symlink(target, link);
}

/**
 * Writes the HIPFIRE_HOME lm-tools owns: model files linked into `models/`
 * (hipfire pairs a tag with its draft and vision sidecar by registry file
 * name), a minimal `config.toml`, and the model catalog. Links to files the
 * deployment no longer declares are removed; real files are never touched.
 */
export async function materializeHipfireHome(
  backend: HipfireBackend,
  modelId: string,
  files: HipfireModelFiles,
): Promise<void> {
  const models = join(backend.home, "models");
  await Deno.mkdir(models, { recursive: true });
  const declared = [files.model, files.draft, files.vision].filter((file): file is string =>
    file !== undefined
  );
  const names = new Set(declared.map((file) => basename(file)));
  for await (const entry of Deno.readDir(models)) {
    if (entry.isSymlink && !names.has(entry.name)) await Deno.remove(join(models, entry.name));
  }
  for (const file of declared) await replaceSymlink(file, join(models, basename(file)));
  await Deno.writeTextFile(
    join(backend.home, "config.toml"),
    "# Generated by lm-tools; rewritten on every start.\nschema_version = 1\n",
  );
  await Deno.writeTextFile(
    join(backend.home, "models.toml"),
    buildHipfireCatalog(backend, modelId, files),
  );
}

/** Starts hipfire serve as the leader of its own process group, so stopping it also stops its daemon. */
export function spawnHipfire(
  backend: HipfireBackend,
  files: HipfireModelFiles,
): Deno.ChildProcess {
  return new Deno.Command("/usr/bin/setsid", {
    args: [backend.executable, ...buildHipfireArgs(backend)],
    env: { ...Deno.env.toObject(), ...buildHipfireEnvironment(backend, files) },
    stdin: "null",
    stdout: "piped",
    stderr: "piped",
  }).spawn();
}
