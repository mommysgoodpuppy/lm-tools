import { assertEquals, assertRejects } from "jsr:@std/assert@1";
import { join } from "jsr:@std/path@1";
import {
  buildHipfireArgs,
  buildHipfireCatalog,
  buildHipfireEnvironment,
  type HipfireBackend,
  hipfireDaemonPath,
  materializeHipfireHome,
} from "./hipfire.ts";
import { hipfireModelFiles, loadDeployment } from "./deployment.ts";

const source = {
  url: "https://example.com/model",
  size: 1,
  sha256: "0".repeat(64),
};

function backend(home: string): HipfireBackend {
  return {
    kind: "hipfire",
    executable: "/opt/hipfire/target/release/hipfire",
    home,
    listen: { host: "127.0.0.1", port: 11535 },
    tag: "qwen3.8:27b-mq4-xts",
    kvMode: "q8",
    maxSeq: 188416,
    ui: true,
    speculative: {
      kind: "dflash",
      model: { path: "/models/qwen38-27b-dflash-mq4.hfq", source },
      blockSize: 16,
    },
    environment: { HIPFIRE_DFLASH_BLOCK: "8", HIPFIRE_EXTRA: "1" },
  };
}

Deno.test("builds hipfire serve arguments and environment", () => {
  const files = { model: "/models/qwen3.8-27b.mq4-xts", vision: "/models/v.hfq" };
  assertEquals(buildHipfireArgs(backend("/home")), [
    "serve",
    "127.0.0.1:11535",
    "--model",
    "qwen3.8:27b-mq4-xts",
    "--spec",
    "dflash",
    "--kv-mode",
    "q8",
    "--max-seq",
    "188416",
    "--ui",
  ]);
  assertEquals(hipfireDaemonPath(backend("/home")), "/opt/hipfire/target/release/daemon");
  assertEquals(buildHipfireEnvironment(backend("/home"), files), {
    HIPFIRE_HOME: "/home",
    HIPFIRE_LOCAL: "1",
    HIPFIRE_DAEMON_BIN: "/opt/hipfire/target/release/daemon",
    HIPFIRE_PREFILL_PROGRESS: "1",
    HIPFIRE_DFLASH_BLOCK: "8",
    HIPFIRE_VISION_MODE: "on",
    HIPFIRE_EXTRA: "1",
  });
});

Deno.test("aliases the client model id to the tag with an explicit model path", () => {
  assertEquals(
    buildHipfireCatalog(backend("/h"), "qwen3.8-27b", { model: "/models/qwen3.8-27b.mq4-xts" }),
    [
      "# Generated by lm-tools; rewritten on every start.",
      "schema_version = 1",
      "",
      "[aliases]",
      '"qwen3.8-27b" = "qwen3.8:27b-mq4-xts"',
      "",
      '[models."qwen3.8:27b-mq4-xts"]',
      'registry_tag = "qwen3.8:27b-mq4-xts"',
      'path = "/h/models/qwen3.8-27b.mq4-xts"',
      "",
    ].join("\n"),
  );
});

Deno.test("materializes the hipfire home with links, catalog and config", async () => {
  const root = await Deno.makeTempDir();
  try {
    const models = join(root, "store");
    await Deno.mkdir(models);
    const model = join(models, "qwen3.8-27b.mq4-xts");
    const draft = join(models, "qwen38-27b-dflash-mq4.hfq");
    await Deno.writeTextFile(model, "m");
    await Deno.writeTextFile(draft, "d");
    const home = join(root, "home");
    await Deno.mkdir(join(home, "models"), { recursive: true });
    await Deno.symlink(join(models, "stale.hfq"), join(home, "models", "stale.hfq"));
    await Deno.writeTextFile(join(home, "models", "kept.bin"), "real file");

    await materializeHipfireHome(backend(home), "qwen3.8-27b", { model, draft });
    await materializeHipfireHome(backend(home), "qwen3.8-27b", { model, draft });

    const entries = [];
    for await (const entry of Deno.readDir(join(home, "models"))) entries.push(entry.name);
    assertEquals(entries.sort(), ["kept.bin", "qwen3.8-27b.mq4-xts", "qwen38-27b-dflash-mq4.hfq"]);
    assertEquals(await Deno.readLink(join(home, "models", "qwen3.8-27b.mq4-xts")), model);
    assertEquals(
      (await Deno.readTextFile(join(home, "models.toml"))).includes(
        '"qwen3.8-27b" = "qwen3.8:27b-mq4-xts"',
      ),
      true,
    );
    assertEquals(
      await Deno.readTextFile(join(home, "config.toml")),
      "# Generated by lm-tools; rewritten on every start.\nschema_version = 1\n",
    );
  } finally {
    await Deno.remove(root, { recursive: true });
  }
});

function deployment(home: string, proxy: boolean): Record<string, unknown> {
  return {
    version: 1,
    name: "qwen-hipfire",
    model: {
      id: "qwen3.8-27b",
      name: "Qwen3.8 27B",
      path: "/models/qwen3.8-27b.mq4-xts",
      source,
      visionProjector: { path: "/models/qwen3.8-27b-vision.hfq", source },
      capabilities: { tools: true, vision: true, reasoning: true, streaming: true },
    },
    runtime: { contextWindow: 188416, maxOutputTokens: 16384, expectedVramMiB: 23000 },
    backend: backend(home),
    compatibility: {
      responsesProxy: proxy
        ? { enabled: true, listen: { host: "127.0.0.1", port: 1235 } }
        : { enabled: false },
    },
  };
}

Deno.test("loads a hipfire deployment and requires the Responses proxy", async () => {
  const root = await Deno.makeTempDir();
  try {
    const path = join(root, "deployment.json");
    await Deno.writeTextFile(path, JSON.stringify(deployment(join(root, "home"), true)));
    const loaded = await loadDeployment(path);
    assertEquals(hipfireModelFiles(loaded.config), {
      model: "/models/qwen3.8-27b.mq4-xts",
      draft: "/models/qwen38-27b-dflash-mq4.hfq",
      vision: "/models/qwen3.8-27b-vision.hfq",
    });
    await Deno.writeTextFile(path, JSON.stringify(deployment(join(root, "home"), false)));
    await assertRejects(
      () => loadDeployment(path),
      Error,
      "hipfire deployments must enable compatibility.responsesProxy",
    );
  } finally {
    await Deno.remove(root, { recursive: true });
  }
});
