import { stringify as stringifyYaml } from "jsr:@std/yaml@1";
import type { FreeRouterModelConfig, FreeRouterServiceConfig } from "./free_router_server.ts";

export interface OmpFreeRouterOptions {
  /** Base URL reachable from the OMP execution environment, including `/v1`. */
  baseUrl: string;
  /** One public lane retained for callers that need a single-model profile. */
  publicModel?: string;
  /** Public lanes exposed together, for example primary and worker roles. */
  publicModels?: string[];
  providerId?: string;
}

export interface FreeRouterPublicModelIdentity {
  id: string;
  contextLength: number;
  maxOutputTokens: number;
  offers: Array<{
    id: string;
    adapter: string;
    provider: string;
    model: string;
    accessClass: string;
    pricing: {
      inputUsdPerMillion: number;
      outputUsdPerMillion: number;
      cacheReadUsdPerMillion?: number;
      cacheWriteUsdPerMillion?: number;
    };
    priority?: number;
  }>;
}

function publicModel(
  config: FreeRouterServiceConfig,
  id: string,
): FreeRouterModelConfig & { contextLength: number; maxOutputTokens: number } {
  const model = config.models.find((candidate) => candidate.id === id);
  if (!model) throw new Error(`Unknown free-router public model: ${id}`);
  if (!model.contextLength || !model.maxOutputTokens) {
    throw new Error(
      `Free-router model ${id} needs contextLength and maxOutputTokens for an OMP profile`,
    );
  }
  return model as FreeRouterModelConfig & { contextLength: number; maxOutputTokens: number };
}

function providerId(value: string): string {
  if (!/^[A-Za-z0-9_-]+$/.test(value)) {
    throw new Error(`OMP free-router provider id is invalid: ${value}`);
  }
  return value;
}

function baseUrl(value: string): string {
  if (!/^https?:\/\//.test(value)) throw new Error(`Invalid OMP free-router base URL: ${value}`);
  return value.replace(/\/+$/, "");
}

function publicModels(
  config: FreeRouterServiceConfig,
  options: OmpFreeRouterOptions,
): Array<FreeRouterModelConfig & { contextLength: number; maxOutputTokens: number }> {
  const ids = options.publicModels ?? (options.publicModel ? [options.publicModel] : []);
  if (ids.length === 0) throw new Error("At least one free-router public model is required");
  if (new Set(ids).size !== ids.length) {
    throw new Error("OMP free-router public models must be unique");
  }
  return ids.map((id) => publicModel(config, id));
}

export function freeRouterPublicModelIdentity(
  config: FreeRouterServiceConfig,
  id: string,
): FreeRouterPublicModelIdentity {
  const model = publicModel(config, id);
  return {
    id: model.id,
    contextLength: model.contextLength,
    maxOutputTokens: model.maxOutputTokens,
    offers: model.offers.map((offer) => ({
      id: offer.id,
      adapter: offer.adapter,
      provider: offer.provider,
      model: offer.model,
      accessClass: offer.accessClass,
      pricing: { ...offer.pricing! },
      ...(offer.priority === undefined ? {} : { priority: offer.priority }),
    })),
  };
}

export function buildOmpFreeRouterProvider(
  config: FreeRouterServiceConfig,
  options: OmpFreeRouterOptions,
): Record<string, unknown> {
  const models = publicModels(config, options);
  const id = providerId(options.providerId ?? "lm-free-router");
  return {
    providers: {
      [id]: {
        baseUrl: baseUrl(options.baseUrl),
        api: "openai-completions",
        auth: "none",
        models: models.map((model) => ({
          id: model.id,
          name: `lm-tools free router: ${model.id}`,
          reasoning: false,
          input: ["text"],
          contextWindow: model.contextLength,
          maxTokens: model.maxOutputTokens,
          cost: { input: 0, output: 0, cacheRead: 0, cacheWrite: 0 },
        })),
      },
    },
  };
}

export function buildOmpFreeRouterModelsYml(
  config: FreeRouterServiceConfig,
  options: OmpFreeRouterOptions,
): string {
  return [
    "# Generated by lm-tools for an OMP attempt profile.",
    stringifyYaml(buildOmpFreeRouterProvider(config, options)).trimEnd(),
    "",
  ].join("\n");
}
